function expected = captureOutputs(qNet, images)
    %captureOutputs - Evaluate the frozen FC and Softmax reference boundaries
    %   EXPECTED = captureOutputs(qNet,IMAGES) evaluates uint8 images with
    %   shape [28 28 1 N] on CPU and returns N-by-10 boundary arrays.
    arguments
        qNet (1,1) dlnetwork
        images {mustBeA(images,'uint8')}
    end
    assert(size(images,1)==28 && size(images,2)==28 && size(images,3)==1 ...
        && ndims(images)<=4 && ~isempty(images), ...
        'mnistverify:InputShape', 'Expected uint8 images of size [28 28 1 N].');
    [fc, scores] = minibatchpredict(qNet, single(images), ...
        Outputs=["fc","softmax"], InputDataFormats="SSCB", ...
        OutputDataFormats=["BC","BC"], MiniBatchSize=32, ...
        ExecutionEnvironment="cpu", Acceleration="none");
    expectedSize = [size(images,4), 10];
    assert(isequal(size(fc),expectedSize) && isequal(size(scores),expectedSize), ...
        'mnistverify:OutputShape', 'Expected N-by-10 FC and Softmax outputs.');
    assert(all(isfinite(double(fc)), 'all') && all(isfinite(double(scores)), 'all'), ...
        'mnistverify:Nonfinite', 'Golden outputs must be finite.');
    expected = struct(FcLogits=fc, Softmax=scores, ...
        DataOrder="batch_class", InputOrder="row_col_channel_batch");
end
